conn = get_connection()
products_db = conn.execute("SELECT product_id, atc_code, name, category_full_name FROM products;").fetchall()
batches_df = pd.read_sql_query("""
    SELECT b.batch_id, b.product_id, p.name as product_name, p.category_full_name,
           b.quantity_on_hand, b.initial_quantity, b.expiry_date, b.received_date
    FROM inventory_batches b
    JOIN products p ON b.product_id = p.product_id
    WHERE b.quantity_on_hand > 0 AND b.received_date <= ?;
""", conn, params=(str(as_of_date),))
sales_df = pd.read_sql_query("""
    SELECT s.sale_date as datum, p.category_full_name as category, s.units_sold
    FROM daily_sales s
    JOIN products p ON s.product_id = p.product_id;
""", conn)
conn.close()

if not products_db:
    st.error("Database is empty. Please run `python src/seed_db.py` to initialize products and sample inventory.")
    st.stop()

if model is None:
    st.error("Model artifact `pharma_catboost_demand_model.pkl` could not be loaded. Check that `catboost` and `joblib` are installed.")
    st.stop()

if sales_df.empty:
    st.error("No sales history found. Please run `python src/seed_db.py` to load daily sales.")
    st.stop()

# Live 28-day forecasts per category using only sales history up to the operational date
feature_row = prepare_inference_row(sales_df, as_of_date)
if feature_row[FEATURE_COLUMNS].isna().any().any():
    st.error(f"Not enough sales history before {as_of_date} to build features (52 weeks required).")
    st.stop()
forecast_map = dict(zip(feature_row['category'], model.predict(feature_row[FEATURE_COLUMNS])))

# -----------------------------------------------------------------------------
# 5. CORE DECISION EVALUATION (TRIAGE)
# -----------------------------------------------------------------------------
triage_summary = []
all_inventory_rows = []
total_units_wasting_soon = 0.0
reorder_count = 0
expiry_risk_count = 0
optimal_count = 0

for prod in products_db:
    p_id = prod['product_id']
    p_name = prod['name']
    p_cat = prod['category_full_name']

    prod_batches = batches_df[batches_df['product_id'] == p_id].to_dict('records') if not batches_df.empty else []
    total_stock = sum(b['quantity_on_hand'] for b in prod_batches)
    demand_28d = max(0.0, float(forecast_map[p_cat]))

    # 1. Evaluate Reorder Need
    reorder_eval = evaluate_reorder_risk(
        product_name=p_name,
        total_stock_on_hand=total_stock,
        predicted_28d_demand=demand_28d,
        lead_time_days=7,
        safety_stock_days=5
    )

    # 2. Evaluate Batch Expiry Risk (FEFO)
    expiry_evals = evaluate_batch_expiry_fefo(
        batches=prod_batches,
        predicted_28d_demand=demand_28d,
        as_of_date_str=str(as_of_date),
        horizon_days=28
    )

    # Calculate total waste projected for this product
    prod_waste = sum(e['expected_waste_units'] for e in expiry_evals)
    total_units_wasting_soon += prod_waste

    # Assess overall status
    needs_attention = False
    primary_issue = []
    action_item = []

    # Expiry check
    if prod_waste > 0:
        needs_attention = True
        expiry_risk_count += 1
        primary_issue.append(f"🔴 Expiry Risk: ~{prod_waste:.0f} units at risk")
        action_item.append(f"Prioritize dispensing or discount {prod_waste:.0f} units expiring soon")

    # Reorder check
    if reorder_eval['reorder_flag'] in ['CRITICAL_STOCKOUT', 'REORDER_SOON']:
        needs_attention = True
        reorder_count += 1
        primary_issue.append(f"🟡 Low Stock: Covers only {reorder_eval['days_of_inventory']} days")
        action_item.append(f"Place replenishment order for ~{reorder_eval['suggested_reorder_qty']:.0f} units")
    elif total_stock > (demand_28d * 2.5):
        primary_issue.append("🔵 Overstocked")
        action_item.append("Sufficient stock; hold purchase orders")
    else:
        if not needs_attention:
            optimal_count += 1
            primary_issue.append("🟢 Healthy Coverage")
            action_item.append("Normal dispensing; no action required")

    # If it needs attention, add to Action Table
    if needs_attention:
        triage_summary.append({
            "Medicine": p_name,
            "Current Stock": f"{total_stock:,.0f} units",
            "Expected 28d Sales": f"~{demand_28d:,.0f} units",
            "Identified Issue": " | ".join(primary_issue),
            "Recommended Action": " | ".join(action_item)
        })

    # Add to complete catalog
    all_inventory_rows.append({
        "Medicine": p_name,
        "Current Stock": total_stock,
        "Forecast (28d)": demand_28d,
        "Stock Coverage": f"{reorder_eval['days_of_inventory']} days",
        "Reorder Status": reorder_eval['reorder_badge'],
        "Expiry Status": "🔴 Expiring Unsold" if prod_waste > 0 else "🟢 Safe"
    })

